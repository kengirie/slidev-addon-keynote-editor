import { open, restore, diff, sleep } from './lib.mjs'
const t = await open(2)
const p = t.page
const [x, y] = await t.s(900, 700)
await p.mouse.click(x, y); await sleep(300)
await p.mouse.click(x, y, { button: 'right' }); await sleep(500)
const items = await p.evaluate(() => [...document.querySelectorAll('.z-context-menu > div')].map(e => e.textContent.trim()).filter(Boolean))
console.log('menu items:', items.slice(0, 6))
const r = await p.evaluate(() => { const m = document.querySelector('.z-context-menu').getBoundingClientRect(); return [m.left, m.top] })
console.log('menu at', r.map(Math.round), 'clicked at', [x, y].map(Math.round))
await p.getByText('テキストを編集', { exact: true }).first().click(); await sleep(500)
console.log('after テキストを編集:', JSON.stringify(await t.state()), await p.evaluate(() => { const s = window.getSelection(); return { collapsed: s.isCollapsed, atEnd: s.anchorOffset } }))
await p.keyboard.press('Escape'); await sleep(1500)
await p.mouse.click(x, y); await sleep(300); await p.mouse.click(x, y, { button: 'right' }); await sleep(500)
await p.getByText('削除（非表示）', { exact: true }).first().click(); await sleep(2500)
console.log('after 削除:', diff().trim().replace(/\n/g, ' | '))
await restore()
console.log('errors', t.errors.filter(e => !/Wake Lock/.test(e)))
await t.browser.close()
