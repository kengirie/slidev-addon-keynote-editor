import { createRequire } from 'node:module'
const require = createRequire('/Users/3001macmini/slidev-keynote-template/package.json')
const { chromium } = require('playwright-chromium')
const sleep = ms => new Promise(r => setTimeout(r, ms))
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
await page.goto('http://localhost:3040/2', { waitUntil: 'networkidle' }); await sleep(1500)
const st = () => page.evaluate(() => ({ docked: document.documentElement.classList.contains('slidev-studio-docked'), editing: window.__studio__.editing.value, sel: window.__studio__.selection.value?.kind, vdrag: !!document.querySelector('#drag-control-container'), text: window.getSelection().toString() }))
const at = async (x, y) => page.evaluate(([x, y]) => { const r = document.querySelector('#slide-content [data-slidev-no="2"]').getBoundingClientRect(); const k = r.width / 1920; return [r.left + x * k, r.top + y * k] }, [x, y])
console.log('開いた直後:', await st())
let [x, y] = await at(300, 140)
await page.mouse.dblclick(x, y); await sleep(600)
console.log('E を押さずにタイトルをダブルクリック:', await st())
await page.keyboard.press('Escape'); await sleep(300); await page.keyboard.press('Escape'); await sleep(2000)
await page.keyboard.press('e'); await sleep(1200)
;[x, y] = await at(300, 140)
await page.mouse.dblclick(x, y); await sleep(600)
console.log('E で閉じてからダブルクリック:', await st())
await browser.close()
